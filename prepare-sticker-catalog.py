def sections(label, folder):
    remaining = sorted((p.name for p in (SOURCE / folder).glob('*.png') if p.name not in EXCLUDED),
                       key=lambda name: (re.sub(r'^\d+-(?:S\d+-)?', '', name), name))
    last_pattern = r'娃娃眼睛' if label == 'Y2K' else r'花|莲|百合|兰' if label == '推荐' else None
    last = [name for name in remaining if last_pattern and re.search(last_pattern, name)]
    remaining = [name for name in remaining if name not in last]
    result = []
    for family, pattern in RULES[label]:
        selected = [name for name in remaining if re.search(pattern, name)]
        if selected:
            result.append((family, selected))
            remaining = [name for name in remaining if name not in selected]
    if remaining:
        result.append(('其他', remaining))
    if last:
        result.append(('娃娃眼睛' if label == 'Y2K' else '花卉', last))
    return result


def generate():
    code = ['// Generated by prepare-sticker-catalog.py from the supplied sticker folders.',
            'const stickerPath = (folder, name) => `./assets/stickers/${folder}/${name.replace(/\\.png$/, ".webp")}`;',
            'const STICKER_CATEGORIES = ' + json.dumps([item[0] for item in CATEGORIES], ensure_ascii=False) + ';']
    catalog = {}
    for label, folder, key in CATEGORIES:
        groups = sections(label, folder)
        names = [name for _, files in groups for name in files]
        code.append('const ' + key + '_STICKERS = ' + json.dumps(names, ensure_ascii=False, indent=2)
                    + '.map(name => stickerPath(' + json.dumps(folder, ensure_ascii=False) + ', name));')
        catalog[label] = key + '_STICKERS'
        print(label, len(names), [(family, len(files)) for family, files in groups])
    code.append('const STICKER_ASSETS = {' + ', '.join(json.dumps(k, ensure_ascii=False) + ': ' + v for k, v in catalog.items()) + '};')
    (ROOT / 'sticker-catalog.js').write_text('\n'.join(code) + '\n', encoding='utf-8')


def contact_sheets():
    from PIL import Image, ImageDraw
    for label, folder, _ in CATEGORIES:
        names = [name for _, files in sections(label, folder) for name in files]
        sheet = Image.new('RGB', (800, ((len(names) + 7) // 8) * 100), '#e9e9ee')
        draw = ImageDraw.Draw(sheet)
        for index, name in enumerate(names):
            with Image.open(SOURCE / folder / name) as image:
                image = image.convert('RGBA')
                bounds = image.getchannel('A').getbbox()
                if bounds:
                    image = image.crop(bounds)
                image.thumbnail((80, 72))
                x, y = index % 8 * 100, index // 8 * 100
                sheet.paste(image, (x + (100 - image.width) // 2, y + (78 - image.height) // 2), image)
                draw.text((x + 4, y + 81), str(index + 1) + ' ' + name.split('-')[0], fill='black')
        sheet.save('/private/tmp/sticker-sheet-' + folder + '.jpg')


